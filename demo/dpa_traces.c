/* Simplified SubBytes operation */
void sub_bytes(unsigned char *state) {
    int i;
    for (i = 0; i < 16; i++) {
        state[i] = sbox[state[i]];
    }
}

/* Simplified ShiftRows operation */
void shift_rows(unsigned char *state) {
    unsigned char temp;
    
    /* Row 1 - shift left by 1 */
    temp = state[1];
    state[1] = state[5];
    state[5] = state[9];
    state[9] = state[13];
    state[13] = temp;
    
    /* Row 2 - shift left by 2 */
    temp = state[2];
    state[2] = state[10];
    state[10] = temp;
    temp = state[6];
    state[6] = state[14];
    state[14] = temp;
    
    /* Row 3 - shift left by 3 */
    temp = state[3];
    state[3] = state[15];
    state[15] = state[11];
    state[11] = state[7];
    state[7] = temp;
}

/* Simplified XOR with key */
void add_round_key(unsigned char *state, const unsigned char *key) {
    int i;
    for (i = 0; i < 16; i++) {
        state[i] ^= key[i];
    }
}

/* Simple encryption - uses just a few rounds for faster execution */
void encrypt_block(unsigned char *plaintext, const unsigned char *key, unsigned char *ciphertext) {
    unsigned char state[16];
    int i, round;
    
    /* Copy plaintext to state */
    for (i = 0; i < 16; i++) {
        state[i] = plaintext[i];
    }
    
    /* Initial round */
    add_round_key(state, key);
    
    /* Main rounds - simplified to 4 rounds for demo */
    for (round = 0; round < 4; round++) {
        sub_bytes(state);
        shift_rows(state);
        add_round_key(state, key);
    }
    
    /* Final round */
    sub_bytes(state);
    shift_rows(state);
    add_round_key(state, key);
    
    /* Copy state to ciphertext */
    for (i = 0; i < 16; i++) {
        ciphertext[i] = state[i];
    }
}

